import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
const require=createRequire('C:/Users/LEE/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/package.json')
const {chromium}=require('playwright')
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'})
try{
 const context=await browser.newContext(),page=await context.newPage(),errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 await context.addInitScript(()=>localStorage.setItem('ieum-v2:user-state:v7',JSON.stringify({songSaves:[{songId:'a-thousand-years'},{songId:'ocean-eyes'}]})))
 await page.goto(process.env.IEUM_QA_URL||'http://127.0.0.1:4207/')
 await page.locator('[data-nav="bookmark"]').click()
 await page.locator('[data-action="collection-tab-songs"]').click()
 await page.locator('[data-action="open-song-save"]').first().click()
 await page.waitForSelector('.detail-screen')
 await page.locator('.project-carousel button').filter({hasText:'Warm Duet'}).click()
 await page.locator('[data-nav="user"]').click()
 await page.locator('[data-nav="bookmark"]').click()
 await page.locator('[data-action="open-song-save"]').nth(1).click()
 await page.waitForSelector('.detail-screen')
 await page.locator('.project-carousel button').filter({hasText:'Low-key Duet'}).click()
 for(let i=0;i<3;i++)await page.goBack()
 await page.waitForSelector('.detail-screen')
 assert.equal(await page.locator('.song-identity h1').textContent(),'A Thousand Years')
 assert.match(await page.locator('.project-carousel button.active').textContent(),/Warm Duet/)
 for(let i=0;i<3;i++)await page.goForward()
 await page.waitForSelector('.detail-screen')
 assert.equal(await page.locator('.song-identity h1').textContent(),'Ocean Eyes','Forward must restore the latest song before leaving its detail')
 assert.match(await page.locator('.project-carousel button.active').textContent(),/Low-key Duet/,'Selected comparison Project must belong to its detail history entry')
 assert.equal(await page.evaluate(()=>window.__IEUM_V2__.state.joined),false)
 assert.equal(await page.evaluate(()=>window.__IEUM_V2__.state.songSaves.length),2)
 assert.deepEqual(errors,[])
 console.log('PASS Song Detail Back/Forward preserves song/comparison Project and saves; no participation or shared server claim')
 await context.close()
}finally{await browser.close()}
