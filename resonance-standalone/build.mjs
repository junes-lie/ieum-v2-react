import {build} from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
const result=await build({entryPoints:[path.join(root,'src/app.js')],bundle:true,format:'iife',minify:true,write:false,legalComments:'inline'});
let html=await fs.readFile(path.join(root,'src/index.html'),'utf8');
const font=await fs.readFile(path.join(root,'public/PretendardVariable.woff2'));
html=html.replace('<style>',`<style>@font-face{font-family:Pretendard;src:url(data:font/woff2;base64,${font.toString('base64')}) format('woff2');font-weight:100 900;font-display:swap;}`);
html=html.replace('<script type="module" src="./app.js"></script>',()=>'<script>'+result.outputFiles[0].text.replaceAll('</script','<\\/script')+'</script>');
const licensePaths=['licenses/THREE-LICENSE.txt','licenses/Pitchy-MIT.txt','licenses/FFT-MIT.txt','licenses/Pretendard-OFL.txt'];
let notices='';for(const name of licensePaths)notices+='\n'+name+'\n'+await fs.readFile(path.join(root,name),'utf8');
html=html.replace('</body>',()=>`<!-- Third-party notices\n${notices.replaceAll('--','—')}\n--></body>`);
await fs.writeFile(path.join(root,'public/IEUM-Resonance.html'),html);
console.log(`Built self-contained HTML: ${Math.round(Buffer.byteLength(html)/1024)} KiB`);
